CREATE TABLE `cuahang` (`id` int(11) NOT NULL AUTO_INCREMENT, `ma_cua_hang` varchar(20) NOT NULL UNIQUE, `ten_cua_hang` varchar(100) NOT NULL, `dia_chi` varchar(255) NOT NULL, `so_dien_thoai` varchar(20) DEFAULT NULL, `trang_thai` tinyint(1) DEFAULT 1, PRIMARY KEY (`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `phanquyen` (`id` int(11) NOT NULL AUTO_INCREMENT, `ten_quyen` varchar(50) NOT NULL, `mo_ta` varchar(255) DEFAULT NULL, PRIMARY KEY (`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `nguoidung` (`id` int(11) NOT NULL AUTO_INCREMENT, `username` varchar(50) NOT NULL UNIQUE, `password` varchar(255) NOT NULL, `phanquyen_id` int(11) NOT NULL, `trang_thai` tinyint(1) DEFAULT 1, PRIMARY KEY (`id`), FOREIGN KEY (`phanquyen_id`) REFERENCES `phanquyen`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `nhanvien` (`id` int(11) NOT NULL AUTO_INCREMENT, `nguoidung_id` int(11) NOT NULL, `cuahang_id` int(11) NOT NULL, `ho_ten` varchar(100) NOT NULL, `so_dien_thoai` varchar(20) DEFAULT NULL, `chuc_vu` varchar(50) DEFAULT NULL, `luong` decimal(15,2) DEFAULT 0.00, `ngay_vao_lam` date DEFAULT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`nguoidung_id`) REFERENCES `nguoidung`(`id`), FOREIGN KEY (`cuahang_id`) REFERENCES `cuahang`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `thetichdiem` (`id` int(11) NOT NULL AUTO_INCREMENT, `hang_the` varchar(50) NOT NULL, `diem_toi_thieu` int(11) NOT NULL DEFAULT 0, `ti_le_giam_gia` decimal(5,2) DEFAULT 0.00, PRIMARY KEY (`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `khachhang` (`id` int(11) NOT NULL AUTO_INCREMENT, `ho_ten` varchar(100) NOT NULL, `so_dien_thoai` varchar(20) NOT NULL UNIQUE, `thetichdiem_id` int(11) DEFAULT NULL, `diem_tich_luy` int(11) DEFAULT 0, `cuahang_id` int(11) NOT NULL, `ngay_dang_ky` datetime DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (`id`), FOREIGN KEY (`thetichdiem_id`) REFERENCES `thetichdiem`(`id`), FOREIGN KEY (`cuahang_id`) REFERENCES `cuahang`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `calamviec` (`id` int(11) NOT NULL AUTO_INCREMENT, `cuahang_id` int(11) NOT NULL, `nhanvien_id` int(11) NOT NULL, `ten_ca` varchar(50) NOT NULL, `thoi_gian_bat_dau` datetime NOT NULL, `thoi_gian_ket_thuc` datetime NOT NULL, `check_in` datetime DEFAULT NULL, `check_out` datetime DEFAULT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`cuahang_id`) REFERENCES `cuahang`(`id`), FOREIGN KEY (`nhanvien_id`) REFERENCES `nhanvien`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `danhmuc` (`id` int(11) NOT NULL AUTO_INCREMENT, `ten_danh_muc` varchar(100) NOT NULL, `mo_ta` text DEFAULT NULL, PRIMARY KEY (`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `nhacungcap` (`id` int(11) NOT NULL AUTO_INCREMENT, `ten_ncc` varchar(100) NOT NULL, `so_dien_thoai` varchar(20) DEFAULT NULL, `dia_chi` varchar(255) DEFAULT NULL, PRIMARY KEY (`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `sanpham` (`id` int(11) NOT NULL AUTO_INCREMENT, `danhmuc_id` int(11) NOT NULL, `ma_san_pham` varchar(50) NOT NULL UNIQUE, `ten_san_pham` varchar(150) NOT NULL, `gia_nhap` decimal(15,2) NOT NULL, `gia_ban` decimal(15,2) NOT NULL, `hinh_anh` text DEFAULT NULL, `trang_thai` tinyint(1) DEFAULT 1, PRIMARY KEY (`id`), FOREIGN KEY (`danhmuc_id`) REFERENCES `danhmuc`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `tonkho` (`id` int(11) NOT NULL AUTO_INCREMENT, `sanpham_id` int(11) NOT NULL, `cuahang_id` int(11) NOT NULL, `so_luong` int(11) NOT NULL DEFAULT 0, PRIMARY KEY (`id`), UNIQUE KEY `uq_tonkho` (`sanpham_id`, `cuahang_id`), FOREIGN KEY (`sanpham_id`) REFERENCES `sanpham`(`id`), FOREIGN KEY (`cuahang_id`) REFERENCES `cuahang`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `phieunhap` (`id` int(11) NOT NULL AUTO_INCREMENT, `cuahang_id` int(11) NOT NULL, `nhacungcap_id` int(11) NOT NULL, `ngay_nhap` datetime DEFAULT CURRENT_TIMESTAMP, `tong_tien` decimal(15,2) DEFAULT 0.00, `nguoi_nhap` int(11) DEFAULT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`cuahang_id`) REFERENCES `cuahang`(`id`), FOREIGN KEY (`nhacungcap_id`) REFERENCES `nhacungcap`(`id`), FOREIGN KEY (`nguoi_nhap`) REFERENCES `nhanvien`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `chitietphieunhap` (`id` int(11) NOT NULL AUTO_INCREMENT, `phieunhap_id` int(11) NOT NULL, `sanpham_id` int(11) NOT NULL, `so_luong` int(11) NOT NULL, `gia_nhap` decimal(15,2) NOT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`phieunhap_id`) REFERENCES `phieunhap`(`id`), FOREIGN KEY (`sanpham_id`) REFERENCES `sanpham`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `phieukiemke` (`id` int(11) NOT NULL AUTO_INCREMENT, `cuahang_id` int(11) NOT NULL, `ngay_kiem_ke` datetime DEFAULT CURRENT_TIMESTAMP, `nhanvien_id` int(11) NOT NULL, `ghi_chu` text DEFAULT NULL, PRIMARY KEY (`id`), FOREIGN KEY (`cuahang_id`) REFERENCES `cuahang`(`id`), FOREIGN KEY (`nhanvien_id`) REFERENCES `nhanvien`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `phieudieuchuyen` (`id` int(11) NOT NULL AUTO_INCREMENT, `tu_cuahang_id` int(11) NOT NULL, `den_cuahang_id` int(11) NOT NULL, `ngay_chuyen` datetime DEFAULT CURRENT_TIMESTAMP, `nguoi_chuyen` int(11) NOT NULL, `trang_thai` varchar(50) DEFAULT 'Đang chuyển', PRIMARY KEY (`id`), FOREIGN KEY (`tu_cuahang_id`) REFERENCES `cuahang`(`id`), FOREIGN KEY (`den_cuahang_id`) REFERENCES `cuahang`(`id`), FOREIGN KEY (`nguoi_chuyen`) REFERENCES `nhanvien`(`id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
